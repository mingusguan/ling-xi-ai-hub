package com.lingxi.identity.api;

/**
 * 常见阻塞原因选项。
 *
 * <p>PRD「新手引导 ONB-01 基础画像」要求该项可跳过，因此用户未选择时集合为空，
 * 不写入任何兜底值——「没回答」和「回答没有阻塞」在业务上是两件事。
 */
public enum CommonBlocker {
  /** 时间不够：日程被其他事情占满。 */
  TIME,
  /** 精力不足：疲劳、身体状态或睡眠影响执行。 */
  ENERGY,
  /** 目标不清：不知道具体该做什么。 */
  CLARITY,
  /** 动力不足：知道怎么做但不想开始。 */
  MOTIVATION,
  /** 环境限制：缺少场地、设备或外部条件。 */
  ENVIRONMENT,
  /** 情绪影响：焦虑、低落等情绪状态干扰执行。 */
  MOOD,
  /** 其他：用户自定义描述由后续复盘补充，这里只标记类别。 */
  OTHER
}
