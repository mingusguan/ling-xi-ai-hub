package com.lingxi.goal.api;

/**
 * 目标类型，取值与 PRD「支持的目标类型」一一对应。
 *
 * <p>该字段同时承担 PRD 数据分析中「按目标大类分析」的维度，因此必须是稳定枚举而不是自由文本。
 */
public enum GoalType {
  /** 学习考试：考证、考研、语言学习。 */
  LEARNING_EXAM,
  /** 职业发展：求职、面试、技能、作品集。 */
  CAREER,
  /** 创作输出：写作、视频、设计作品。 */
  CREATIVE,
  /** 阅读与知识：阅读计划、专题学习。 */
  READING,
  /** 习惯养成：早起、整理、专注。 */
  HABIT,
  /** 健身与作息：日常运动、规律睡眠。 */
  FITNESS,
  /** 旅行与活动：行程准备、清单、预算。 */
  TRAVEL,
  /** 人际沟通：沟通准备、关系维护提醒。 */
  COMMUNICATION,
  /** 个人预算：储蓄目标、一般预算记录。 */
  BUDGET,
  /** 情绪记录：日记、自我观察、压力记录。 */
  EMOTION
}
