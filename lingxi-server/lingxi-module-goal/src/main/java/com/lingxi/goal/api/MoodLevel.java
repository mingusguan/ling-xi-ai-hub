package com.lingxi.goal.api;

/**
 * 打卡时的情绪自评，五档中性量表。
 *
 * <p>只用于复盘时观察趋势与调整节奏，不产出任何诊断结论，也不作为风险判定依据：
 * 风险识别由安全链路负责，两件事不共用一套信号，避免把日常情绪波动当成危机，
 * 也避免用户因为担心被判定而不敢如实记录。
 */
public enum MoodLevel {
  /** 明显低落。 */
  VERY_LOW,
  /** 偏低。 */
  LOW,
  /** 平稳。 */
  NEUTRAL,
  /** 不错。 */
  GOOD,
  /** 很好。 */
  VERY_GOOD
}
